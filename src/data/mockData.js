export const generateInterpolatedRoute = (startCoord, endCoord, numWaypoints = 5) => {
  const points = [];
  points.push([startCoord.lat, startCoord.lng]);
  for (let i = 1; i <= numWaypoints; i++) {
    const t = i / (numWaypoints + 1);
    // Add realistic road deviation curve
    const jitterLat = Math.sin(t * Math.PI) * 0.008;
    const jitterLng = Math.cos(t * Math.PI) * 0.006;
    const lat = startCoord.lat + (endCoord.lat - startCoord.lat) * t + jitterLat;
    const lng = startCoord.lng + (endCoord.lng - startCoord.lng) * t + jitterLng;
    points.push([Number(lat.toFixed(4)), Number(lng.toFixed(4))]);
  }
  points.push([endCoord.lat, endCoord.lng]);
  return points;
};

